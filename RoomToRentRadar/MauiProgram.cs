using CommunityToolkit.Maui;
using Microsoft.Extensions.Logging;
using RoomToRentRadar.Features.Alerts;
using RoomToRentRadar.Features.Auth;
using RoomToRentRadar.Features.Comparison;
using RoomToRentRadar.Features.Favorites;
using RoomToRentRadar.Features.Home;
using RoomToRentRadar.Features.Landlord;
using RoomToRentRadar.Features.Map;
using RoomToRentRadar.Features.Reports;
using RoomToRentRadar.Features.Rooms;
using RoomToRentRadar.Infrastructure.DependencyInjection;
using Syncfusion.Maui.Toolkit.Hosting;

namespace RoomToRentRadar
{
    /// <summary>
    /// Composition Root (LOCKED BY @architect).
    /// Feature developers DO NOT edit this file — register your services and Shell routes inside
    /// your feature's <c>Features/&lt;FeatureName&gt;/&lt;FeatureName&gt;FeatureModule.cs</c> instead.
    /// </summary>
    public static class MauiProgram
    {
        public static MauiApp CreateMauiApp()
        {
            var builder = MauiApp.CreateBuilder();
            builder
                .UseMauiApp<App>()
                .UseMauiCommunityToolkit()
                .ConfigureSyncfusionToolkit()
                .ConfigureMauiHandlers(handlers =>
                {
#if WINDOWS
                    Microsoft.Maui.Controls.Handlers.Items.CollectionViewHandler.Mapper.AppendToMapping("KeyboardAccessibleCollectionView", (handler, view) =>
                    {
                        handler.PlatformView.SingleSelectionFollowsFocus = false;
                    });
#endif
                })
                .ConfigureFonts(fonts =>
                {
                    fonts.AddFont("OpenSans-Regular.ttf", "OpenSansRegular");
                    fonts.AddFont("OpenSans-Semibold.ttf", "OpenSansSemibold");
                    fonts.AddFont("SegoeUI-Semibold.ttf", "SegoeSemibold");
                    fonts.AddFont("FluentSystemIcons-Regular.ttf", FluentUI.FontFamily);
                });

#if DEBUG
            builder.Logging.AddDebug();
            builder.Services.AddLogging(configure => configure.AddDebug());
#endif

            // 1. UI error handling & baseline Home screen
            builder.Services.AddSingleton<IErrorHandler, ModalErrorHandler>();
            builder.Services.AddSingleton<ModalErrorHandler>();
            builder.Services.AddTransient<HomePageModel>();
            builder.Services.AddTransient<HomePage>();

            // 2. Feature Modules (each developer registers their own services & routes inside their FeatureModule file)
            builder.Services
                .AddAuthFeature()
                .AddRoomsFeature()
                .AddMapFeature()
                .AddFavoritesFeature()
                .AddAlertsFeature()
                .AddLandlordFeature()
                .AddComparisonFeature()
                .AddReportsFeature();

            // 3. Shared SQLite Infrastructure + TryAddSingleton In-Memory Fakes (fallback for unmerged backend tasks)
            var dbPath = $"Data Source={Path.Combine(FileSystem.AppDataDirectory, Constants.DatabaseFilename)}";
            builder.Services.AddRentalInfrastructure(dbPath);

            return builder.Build();
        }
    }
}

    /// <summary>
    /// Builds one demo row. Verified/PendingReview lifecycle fields follow BR-LST-04/06:
    /// only <see cref="ListingStatus.Available"/> rows carry <c>VerifiedAtUtc</c> + <c>PublishedAtUtc</c>;
    /// Rented rows were verified before being rented.
    /// </summary>
    private static Room Create(
        int minuteOffset,
        string id,
        string title,
        RoomType roomType,
        long monthlyRentVnd,
        double areaM2,
        string addressLine,
        string ward,
        string district,
        double latitude,
        double longitude,
        ListingStatus status,
        string description,
        int maxOccupants,
        string furnishing,
        long electricityPriceVndPerKwh,
        long waterPriceVnd,
        string waterPriceUnit,
        long internetFeeVnd,
        long parkingFeeVnd,
        string? otherFeesNote,
        string? statusReason,
        bool isSafetyVerified)
    {
        var createdAtUtc = BaseCreatedAtUtc.AddMinutes(minuteOffset);
        var verifiedAtUtc = status is ListingStatus.Available or ListingStatus.Rented
            ? createdAtUtc.AddMinutes(30)
            : (DateTime?)null;
        var publishedAtUtc = status == ListingStatus.Available
            ? verifiedAtUtc
            : null;

        return Room.Reconstitute(
            id: id,
            landlordId: LandlordId,
            title: title,
            roomType: roomType,
            monthlyRentVnd: monthlyRentVnd,
            depositVnd: monthlyRentVnd,
            areaM2: areaM2,
            addressLine: addressLine,
            ward: ward,
            district: district,
            latitude: latitude,
            longitude: longitude,
            status: status,
            createdAtUtc: createdAtUtc,
            lastUpdatedAtUtc: createdAtUtc,
            version: 1,
            description: description,
            maxOccupants: maxOccupants,
            furnishing: furnishing,
            availableFrom: BaseAvailableFrom,
            electricityPriceVndPerKwh: electricityPriceVndPerKwh,
            waterPriceVnd: waterPriceVnd,
            waterPriceUnit: waterPriceUnit,
            internetFeeVnd: internetFeeVnd,
            parkingFeeVnd: parkingFeeVnd,
            otherFeesNote: otherFeesNote,
            statusReason: statusReason,
            needsReReview: false,
            isSafetyVerified: isSafetyVerified,
            verifiedAtUtc: verifiedAtUtc,
            verifiedByUserId: null, // no seed Users row exists yet → keep the FK dangling-free (ERD §4.4)
            publishedAtUtc: publishedAtUtc);
    }
